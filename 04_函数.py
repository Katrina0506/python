say_hello()        # 可以调用任意多次


# ============================================================
# 2. 带参数的函数：把外面的数据传进去
# ============================================================

def greet(name):
    print(f"你好，{name}！")


greet("小明")
greet("小红")


# 参数可以有默认值。有默认值的参数要放在后面
def greet2(name, title="老师"):
    print(f"你好，{title} {name}")


greet2("张三")              # 用默认的 title
greet2("李四", "主任")       # 覆盖默认值
greet2(title="校长", name="王五")   # 也可以按名字指定，顺序就随便了


# ============================================================
# 3. 返回值 return：把计算结果交回给调用者
#    return 之后的代码不会被执行
# ============================================================

def average(numbers):
    """求平均值（这行叫文档字符串，用 help(average) 可以看）"""
    if len(numbers) == 0:
        return 0            # 防止除以 0 出错
    return sum(numbers) / len(numbers)


print(average([88, 92, 76]))          # 85.333...
print(round(average([88, 92, 76]), 1))

# 函数可以返回多个值（其实是打包成了一个元组）
def score_stats(numbers):
    return max(numbers), min(numbers), round(average(numbers), 1)


top, low, avg = score_stats([88, 92, 76, 95, 60])
print(f"最高 {top}，最低 {low}，平均 {avg}")


# 【物理味】把公式封装成函数，反复调用
def fall_time(height, g=9.8):
    """自由落体：已知高度 h，求落地时间 t = sqrt(2h/g)"""
    return (2 * height / g) ** 0.5


for h in [5, 20, 45]:
    print(f"从 {h} 米落下约需 {fall_time(h):.2f} 秒")


def kinetic_energy(mass, speed):
    """动能 Ek = 1/2 * m * v^2"""
    return 0.5 * mass * speed ** 2


print("动能 =", kinetic_energy(2, 3), "焦耳")


