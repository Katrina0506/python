# ============================================================
# 1. 数字：整数 int、小数 float
# ============================================================

a = 7
b = 2

print(a + b)      # 加  -> 9
print(a - b)      # 减  -> 5
print(a * b)      # 乘  -> 14
print(a / b)      # 除  -> 3.5     注意：除法结果一定是小数
print(a // b)     # 整除 -> 3       只要整数部分
print(a % b)      # 取余 -> 1       用来判断奇偶很常见
print(a ** b)     # 乘方 -> 49

print(round(3.14159, 3))     # 四舍五入到 3 位小数
print(abs(-5))               # 绝对值 -> 5

# 【物理味】匀加速直线运动
v0, acc, t = 10, 2, 5                  # 一行同时给多个变量赋值
displacement = v0 * t + 0.5 * acc * t ** 2
print(f"5 秒内位移 = {displacement} 米")


# ============================================================
# 2. 字符串 str：一串文字
# ============================================================

s = "  高中物理  "

print(len(s))              # 长度（包含空格）-> 8
print(s.strip())           # 去掉两边空白 -> "高中物理"
print(s.strip().replace("高中", "初中"))    # 替换文字 -> "初中物理"
print("物理" in s)          # 判断是否包含 -> True
print(s.strip().split("物"))  # 按“物”切开 -> ['高', '理']

# 拼接
print("高一" + "物理")        # 用 + 拼
print("高一" * 3)             # 用 * 重复 -> 高一高一高一

# 切片：按位置取出其中一段。位置从 0 开始数
word = "加速度"
#        0 1 2
print(word[0])        # 第 1 个字 -> 加
print(word[-1])       # 最后 1 个字 -> 度
print(word[0:2])      # 从 0 到 2（不含 2）-> 加速
print(word[::-1])     # 倒过来 -> 度速加


# ============================================================
# 3. 列表 list：一串**有顺序**的数据，可以修改
#    用方括号 [] 表示
# ============================================================

scores = [88, 92, 76, 95, 60]

print(scores)              # 整个列表
print(scores[0])           # 第 1 个 -> 88
print(scores[-1])          # 最后 1 个 -> 60
print(scores[1:3])         # 切片 -> [92, 76]
print(len(scores))         # 有几个 -> 5
print(max(scores))         # 最大 -> 95
print(min(scores))         # 最小 -> 60
print(sum(scores))         # 总和
print(sum(scores) / len(scores))   # 平均分

scores.append(100)         # 末尾追加一个
print("追加后：", scores)

scores.sort()              # 从小到大排序（会改变原列表）
print("排序后：", scores)

scores.sort(reverse=True)  # 从大到小
print("倒序后：", scores)

# 【物理味】用列表存一组实验数据，统一处理
masses = [0.5, 1.0, 1.5, 2.0]
print("总质量 =", sum(masses), "kg")


# ============================================================
# 4. 字典 dict：一串**有名字**的数据，用 键: 值 成对存放
#    用花括号 {} 表示。查数据的时候比列表更直观
# ============================================================

student = {
    "name": "小明",
    "class": "高一(3)班",
    "score": 92,
    "is_pass": True,
}

print(student["name"])            # 用键取值 -> 小明
print(student.get("score"))       # 同样取值，更安全的写法
print(student.get("age", "没记录"))  # 键不存在时给个默认值

student["score"] = 95             # 修改
student["seat"] = 12             # 新增
print(student)

print(list(student.keys()))       # 所有键
print(list(student.values()))     # 所有值

# 【物理味】用字典存一个“班级”的学生名单
classroom = [
    {"name": "小明", "score": 92},
    {"name": "小红", "score": 88},
    {"name": "小刚", "score": 75},
]

for stu in classroom:
    print(f"{stu['name']} 考了 {stu['score']} 分")

# 列表套字典，是实际工作里最常见的数据结构。第 5、6 课还会用到。


# ============================================================
# 5. 类型转换
# ============================================================

print(int("42") + 1)        # 字符串 -> 整数
print(float("3.14") * 2)    # 字符串 -> 小数
print(str(100) + "分")       # 数字 -> 字符串
print(bool(0), bool(1))     # 数字 -> 布尔：0 是 False，非 0 是 True

