# ============================================================
# 1. if：满足条件才执行
#    Python 靠**缩进**（行首的空格）来判断哪些代码属于 if。
#    缩进一般是 4 个空格，别用 Tab 混着来。
# ============================================================

score = 78

if score >= 60:
    print("及格了")

print("这句话永远会执行（因为它在 if 外面）")


# ============================================================
# 2. if / elif / else：多条路选一条
# ============================================================

def grade(s):
    """根据分数返回等级（这个词叫“函数”，第 4 课细讲，这里先用）"""
    if s >= 90:
        return "优秀"
    elif s >= 80:
        return "良好"
    elif s >= 60:
        return "及格"
    else:
        return "不及格"


for s in [95, 82, 61, 40]:
    print(f"{s} 分 -> {grade(s)}")

# 比较运算符：>  <  >=  <=  ==（相等）  !=（不等）
# 逻辑运算符：and（并且） or（或者） not（不是）

score = 85
attendance = 0.9
if score >= 80 and attendance >= 0.8:
    print("可以评优")

if score < 60 or attendance < 0.7:
    print("需要重点关注")


# ============================================================
# 3. for：把一串东西挨个处理一遍（最常用）
# ============================================================

for subject in ["物理", "化学", "生物"]:
    print("今天要上：", subject)

# range(n) 生成 0,1,2,...,n-1
for i in range(3):
    print("第", i, "次循环")

# range(起, 止) 从“起”开始，到“止”之前结束
for i in range(1, 6):
    print(f"第 {i} 题")

# enumerate 同时拿到“序号”和“内容”，序号默认从 0 开始
names = ["小明", "小红", "小刚"]
for index, name in enumerate(names, start=1):
    print(f"第 {index} 名：{name}")

# 【物理味】遍历一组测量数据
data = [9.8, 9.7, 9.9, 9.8, 10.0]
total = 0
for value in data:
    total = total + value
print("平均值 =", round(total / len(data), 3))

# 字典也能遍历
student = {"name": "小明", "score": 92}
for key, value in student.items():
    print(key, "=", value)


# ============================================================
# 4. while：条件成立就一直重复（要小心变成死循环）
# ============================================================

count = 3
while count > 0:
    print("倒计时", count)
    count -= 1          # 少了这一行就会永远循环下去！
print("发射！")


# ============================================================
# 5. break / continue：提前跳出、跳过本次
# ============================================================

for n in range(1, 10):
    if n == 4:
        continue        # 遇到 4 就跳过，不打印
    if n == 7:
        break           # 遇到 7 直接结束整个循环
    print("n =", n)


# ============================================================
# 6. 列表推导式：一行生成新列表（看着高级，用熟很快就离不开）
# ============================================================

scores = [72, 85, 90, 66, 100, 58]

passed = [s for s in scores if s >= 60]        # 挑出及格的
print("及格的分数：", passed)

curved = [s + 5 for s in scores]               # 全部加 5 分
print("加分后：", curved)

doubled = [s * 2 for s in scores]
print("翻倍：", doubled)

print("\n==== 第 3 课结束 ====")


