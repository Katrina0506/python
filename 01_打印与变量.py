# 以 # 开头的是单行注释
# 上面这三行以 """ 包裹的内容叫“文档字符串”，通常写在文件开头说明用途


# ============================================================
# 2. print(...)：把括号里的内容显示到屏幕上
# ============================================================

print("你好，Python！")          # 字符串要用引号包起来
print(1 + 2)                     # 括号里也可以放算式，Python 先算再打印
print("1 + 2 =", 1 + 2)          # 用逗号可以一次打印好几样东西，逗号会变成空格
print()                          # 空括号 = 打印一个空行


# ============================================================
# 3. 变量：给一个值起个名字，方便反复使用
#    语法就是：  名字 = 值      （这个 = 是“赋值”，不是数学上的等于）
# ============================================================

student_name = "小明"
score = 92.5
is_pass = True

print(student_name)
print(score)
print(is_pass)

# 变量可以重新赋值，也可以拿旧值算新值
score = score + 5          # 也可以写成 score += 5
print("加分后：", score)

# 【物理味】自由落体：t = sqrt(2h/g)
g = 9.8
height = 20
time = (2 * height / g) ** 0.5      # ** 0.5 就是开平方
print("从 20 米落下需要", time, "秒")

# 想让输出好看点，用 round(值, 小数位数)
print("保留 2 位小数：", round(time, 2), "秒")


# ============================================================
# 4. f-string：把变量嵌进一句话里（最常用的字符串写法）
#    在引号前加个小写 f，变量用花括号 {} 括起来
# ============================================================

print(f"学生 {student_name} 的得分是 {score} 分")
print(f"下落时间约 {time:.2f} 秒")      # :.2f 表示保留 2 位小数
print(f"1 + 2 的结果是 {1 + 2}")        # 花括号里可以直接写算式


# ============================================================
# 5. 查看类型：不确定一个变量是什么类型时，用 type()
# ============================================================

print(type(student_name))   # <class 'str'>    字符串
print(type(score))          # <class 'float'>  小数
print(type(3))              # <class 'int'>    整数
print(type(is_pass))        # <class 'bool'>   布尔值


# ============================================================
# 6. input()：等待用户从键盘输入一行文字
#    注意：input() 拿到的**永远是字符串**，想当数字用必须转换
# ============================================================

# 用 try/except 包起来，是为了让这个文件在“没有键盘输入”的情况下也能跑完
# （比如被别的程序调用时）。你自己在 PyCharm 里运行时，正常输入即可。
try:
    name = input("请输入你的名字，然后按回车：")
    print(f"你好，{name}！欢迎开始学 Python。")

    raw = input("随便输入一个整数：")
    number = int(raw)                 # int(...) 把字符串转成整数
    print(f"你说的数字翻倍是：{number * 2}")
except EOFError:
    print("（没有检测到键盘输入，已跳过 input 演示——在你自己的电脑上运行就会正常提问）")

print("\n==== 第 1 课结束 ====")


